export function ErrorState({ error, retry }: { error: unknown; retry?: () => void }) {
  return (
    <div className="state error" role="alert">
      <XOctagon aria-hidden />
      <b style={{ color: 'var(--text)' }}>Something went wrong</b>
      <span className="small">{error instanceof Error ? error.message : String(error)}</span>
      {retry && <Button onClick={retry}>Try again</Button>}
    </div>
  );
}

export function Callout({ tone = 'info', children, title }: { tone?: 'info' | 'warn' | 'bad' | 'ok'; children: ReactNode; title?: string }) {
  const Icon = tone === 'bad' ? XOctagon : tone === 'warn' ? AlertTriangle : tone === 'ok' ? CheckCircle2 : Info;
  return (
    <div className={`callout ${tone}`} role={tone === 'bad' ? 'alert' : undefined}>
      <Icon aria-hidden className={tone === 'bad' ? 'neg' : tone === 'warn' ? 'warn' : tone === 'ok' ? 'pos' : ''} style={tone === 'info' ? { color: 'var(--blue)' } : undefined} />
      <div className="small">
        {title && <b style={{ display: 'block', color: 'var(--text)', marginBottom: 2 }}>{title}</b>}
        {children}
      </div>
    </div>
  );
}

function useFocusTrap(open: boolean, onClose: () => void) {
  const ref = useRef<HTMLDivElement>(null);
  useEffect(() => {
    if (!open) return;
    const prev = document.activeElement as HTMLElement | null;
    const el = ref.current;
    const focusables = () => Array.from(el?.querySelectorAll<HTMLElement>('button:not([disabled]), [href], input:not([disabled]), select:not([disabled]), textarea, [tabindex]:not([tabindex="-1"])') ?? []);
    setTimeout(() => (el?.querySelector<HTMLElement>('[data-autofocus]') ?? focusables()[0])?.focus(), 0);
    const onKey = (e: KeyboardEvent) => {
      if (e.key === 'Escape') {
        e.stopPropagation();
        onClose();
      }
      if (e.key === 'Tab') {
        const f = focusables();
        if (!f.length) return;
        if (e.shiftKey && document.activeElement === f[0]) {
          e.preventDefault();
          f[f.length - 1].focus();
        } else if (!e.shiftKey && document.activeElement === f[f.length - 1]) {
          e.preventDefault();
          f[0].focus();
        }
      }
    };
    document.addEventListener('keydown', onKey);
    return () => {
      document.removeEventListener('keydown', onKey);
      prev?.focus?.();
    };
  }, [open, onClose]);
  return ref;
}

export function Modal({ open, onClose, title, children, footer, wide, labelExtra }: { open: boolean; onClose: () => void; title: ReactNode; children: ReactNode; footer?: ReactNode; wide?: boolean; labelExtra?: ReactNode }) {
  const ref = useFocusTrap(open, onClose);
  const id = useId();
  if (!open) return null;
  return (
    <div className="overlay" onMouseDown={(e) => e.target === e.currentTarget && onClose()}>
      <div className={`modal ${wide ? 'wide' : ''}`} role="dialog" aria-modal="true" aria-labelledby={id} ref={ref}>
        <div className="modal-head">
          <div className="row">
            <h2 id={id}>{title}</h2>
            {labelExtra}
          </div>
          <button className="btn ghost icon" onClick={onClose} aria-label="Close dialog">
            <X aria-hidden />
          </button>
        </div>
        <div className="modal-body">{children}</div>
        {footer && <div className="modal-foot">{footer}</div>}
      </div>
    </div>
  );
}

export function Drawer({ open, onClose, title, children, footer, labelExtra }: { open: boolean; onClose: () => void; title: ReactNode; children: ReactNode; footer?: ReactNode; labelExtra?: ReactNode }) {
  const ref = useFocusTrap(open, onClose);
  const id = useId();
  if (!open) return null;
  return (
    <div className="overlay drawer-overlay" onMouseDown={(e) => e.target === e.currentTarget && onClose()}>
      <aside className="drawer" role="dialog" aria-modal="true" aria-labelledby={id} ref={ref}>
        <div className="modal-head">
          <div className="row">
            <h2 id={id}>{title}</h2>
            {labelExtra}
          </div>
          <button className="btn ghost icon" onClick={onClose} aria-label="Close panel">
            <X aria-hidden />
          </button>
        </div>
        <div className="modal-body" style={{ flex: 1 }}>{children}</div>
        {footer && <div className="modal-foot">{footer}</div>}
      </aside>
    </div>
  );
}

export function Confirm({ open, title, children, confirmLabel = 'Confirm', danger, onConfirm, onClose, busy, requireText }: { open: boolean; title: string; children: ReactNode; confirmLabel?: string; danger?: boolean; onConfirm: () => void; onClose: () => void; busy?: boolean; requireText?: string }) {
  const [typed, setTyped] = useState('');
  useEffect(() => setTyped(''), [open]);
  return (
    <Modal
      open={open}
      onClose={onClose}
      title={title}
      footer={
        <>
          <Button onClick={onClose}>Cancel</Button>
          <Button variant={danger ? 'danger' : 'primary'} onClick={onConfirm} loading={busy} disabled={!!requireText && typed !== requireText}>
            {confirmLabel}
          </Button>
        </>
      }
    >
      <div className="stack">
        {children}
        {requireText && (
          <Field label={`Type "${requireText}" to confirm`}>
            <input className="input" value={typed} onChange={(e) => setTyped(e.target.value)} data-autofocus />
          </Field>
        )}
      </div>
    </Modal>
  );
}

export function Field({ label, hint, error, children, htmlFor }: { label: ReactNode; hint?: ReactNode; error?: string | null; children: ReactNode; htmlFor?: string }) {
  return (
    <div className="field">
      <label htmlFor={htmlFor}>{label}</label>
      {children}
      {hint && !error && <span className="hint">{hint}</span>}
      {error && (
        <span className="err" role="alert">
          {error}
        </span>
      )}
    </div>
  );
}

/** rupee amount input: shows rupees, emits paise */
export function MoneyInput({ id, value, onChange, min = 0, step = 1000, ...rest }: { id?: string; value: number; onChange: (paise: number) => void; min?: number; step?: number; disabled?: boolean; 'aria-invalid'?: boolean }) {
  return (
    <div style={{ position: 'relative' }}>
      <span style={{ position: 'absolute', left: 10, top: '50%', transform: 'translateY(-50%)', color: 'var(--text-3)' }} aria-hidden>
        ₹
      </span>
      <input id={id} className="input num" style={{ paddingLeft: 24 }} type="number" inputMode="decimal" min={min} step={step} value={Number.isFinite(value) ? value / 100 : ''} onChange={(e) => onChange(Math.round(Number(e.target.value || 0) * 100))} {...rest} />
    </div>
  );
}

export function Tabs<T extends string>({ tabs, value, onChange, label }: { tabs: { id: T; label: ReactNode }[]; value: T; onChange: (t: T) => void; label: string }) {
  return (
    <div className="tabs" role="tablist" aria-label={label}>
      {tabs.map((t) => (
        <button
          key={t.id}
          role="tab"
          aria-selected={value === t.id}
          tabIndex={value === t.id ? 0 : -1}
          onClick={() => onChange(t.id)}
          onKeyDown={(e) => {
            const i = tabs.findIndex((x) => x.id === value);
            if (e.key === 'ArrowRight') onChange(tabs[(i + 1) % tabs.length].id);
            if (e.key === 'ArrowLeft') onChange(tabs[(i - 1 + tabs.length) % tabs.length].id);
          }}
        >
          {t.label}
        </button>
      ))}
    </div>
  );
}

export function Seg<T extends string>({ options, value, onChange, label }: { options: { id: T; label: ReactNode }[]; value: T; onChange: (v: T) => void; label: string }) {
  return (
    <div className="seg" role="group" aria-label={label}>
      {options.map((o) => (
        <button key={o.id} type="button" aria-pressed={value === o.id} onClick={() => onChange(o.id)}>
          {o.label}
        </button>
      ))}
    </div>
  );
}

export function Meter({ value, tone, label }: { value: number; tone?: 'blue' | 'amber' | 'red'; label: string }) {
  const v = Math.max(0, Math.min(1, value));
  return (
    <div className={`meter ${tone ?? ''}`} role="meter" aria-valuemin={0} aria-valuemax={100} aria-valuenow={Math.round(v * 100)} aria-label={label}>
      <i style={{ width: `${v * 100}%` }} />
    </div>
  );
}

export function Stat({ label, value, sub, dataType }: { label: ReactNode; value: ReactNode; sub?: ReactNode; dataType?: DataType }) {
  return (
    <div className="stat">
      <span className="l row">
        {label}
        {dataType && dataType !== 'actual' && <DataTypeBadge type={dataType} />}
      </span>
      <span className="v num">{value}</span>
      {sub && <span className="small faint">{sub}</span>}
    </div>
  );
}

export function Table({ head, children, compact, caption }: { head: ReactNode; children: ReactNode; compact?: boolean; caption?: string }) {
  return (
    <div className="table-wrap">
      <table className={`t ${compact ? 'compact' : ''}`}>
        {caption && <caption className="sr-only">{caption}</caption>}
        <thead>{head}</thead>
        <tbody>{children}</tbody>
      </table>
    </div>
  );
}

export function Pager({ total, offset, limit, onChange }: { total: number; offset: number; limit: number; onChange: (o: number) => void }) {
  if (total <= limit) return null;
  return (
    <div className="row between mt">
      <span className="small muted">
        {offset + 1}–{Math.min(total, offset + limit)} of {total.toLocaleString('en-IN')}
      </span>
      <div className="row">
        <Button size="sm" disabled={offset === 0} onClick={() => onChange(Math.max(0, offset - limit))}>
          Previous
        </Button>
        <Button size="sm" disabled={offset + limit >= total} onClick={() => onChange(offset + limit)}>
          Next
        </Button>
      </div>
    </div>
  );
}
