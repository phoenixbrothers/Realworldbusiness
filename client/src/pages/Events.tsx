/** Business news & events: simulated world events with company-specific exposure, plus company notifications. */
import { useMemo, useState } from 'react';
import { useSearchParams } from 'react-router-dom';
import { useWorld } from '../store';
import { inr } from '../format';
import { PageHeader } from '../components/Shell';
import { EventDetail, exposureTone } from '../components/EventDetail';
import { Badge, Callout, DataTypeBadge, Empty, Panel, Seg, SeverityBadge, severityTone } from '../components/ui';

export default function Events() {
  const { view } = useWorld();
  const [params] = useSearchParams();
  const [sel, setSel] = useState<string | null>(params.get('focus'));
  const [status, setStatus] = useState<'all' | 'active' | 'expired'>('all');
  const [exposed, setExposed] = useState<'all' | 'exposed'>('all');
  const [tab, setTab] = useState<'world' | 'company'>('world');
  const w = view!.world;
  const c = view!.company;
  const exp = (id: string) => c?.computed.exposures.find((x) => x.eventId === id);
  const events = useMemo(() => [...w.events].reverse().filter((e) => (status === 'all' || e.status === status) && (exposed === 'all' || (exp(e.id) && exp(e.id)!.level !== 'none'))), [w.events, status, exposed, c]); // eslint-disable-line react-hooks/exhaustive-deps
  const ev = w.events.find((e) => e.id === sel);
  return (
    <>
      <PageHeader title="Business news & events" module="events" />
      <Callout tone="warn" title="All events are simulated">These are generated by the simulation from explicit rules. They are not real-world news and do not predict real events.</Callout>
      <div className="row mt mb">
        <Seg label="Feed" value={tab} onChange={setTab} options={[{ id: 'world', label: 'World events' }, { id: 'company', label: 'Company notifications' }]} />
        {tab === 'world' && (
          <>
            <Seg label="Status" value={status} onChange={setStatus} options={[{ id: 'all', label: 'All' }, { id: 'active', label: 'Active' }, { id: 'expired', label: 'Expired' }]} />
            {c && <Seg label="Exposure" value={exposed} onChange={setExposed} options={[{ id: 'all', label: 'Everything' }, { id: 'exposed', label: 'Affects me' }]} />}
          </>
        )}
      </div>
      {tab === 'world' ? (
        <Panel actions={<DataTypeBadge type="simulated" />} title={`${events.length} event(s)`}>
          {events.length === 0 ? <Empty title="No events match">Events are generated when months are run.</Empty> : (
            <div className="list">
              {events.map((e) => {
                const x = exp(e.id);
                return (
                  <button key={e.id} className="list-item" onClick={() => setSel(e.id)}>
                    <SeverityBadge severity={e.severity} />
                    <span style={{ flex: 1 }}>
                      <b style={{ display: 'block' }}>{e.title}</b>
                      <span className="small muted">{e.summary}</span>
                      <span className="small faint" style={{ display: 'block' }}>{e.tickLabel}{e.endTick > e.tick ? ` → ${e.endLabel}` : ''} · {e.status} · confidence {(e.confidence * 100).toFixed(0)}%</span>
                    </span>
                    {x && <span className="stack" style={{ alignItems: 'flex-end', gap: 4 }}><Badge tone={exposureTone(x.level)}>exposure: {x.level}</Badge>{x.monthlyImpact !== 0 && x.level !== 'none' && <span className="small">{inr(Math.abs(x.monthlyImpact), { compact: true })}/mo</span>}</span>}
                  </button>
                );
              })}
            </div>
          )}
        </Panel>
      ) : (
        <Panel title="Company notifications">
          {w.notifications.length === 0 ? <Empty title="No notifications" /> : (
            <div className="list">
              {w.notifications.map((n) => (
                <div key={n.id} className="list-item">
                  <Badge tone={severityTone(n.severity)}>{n.kind}</Badge>
                  <span style={{ flex: 1 }}><b className="small" style={{ display: 'block' }}>{n.title}</b><span className="small muted">{n.body}</span></span>
                  <span className="small faint">{n.tickLabel}</span>
                </div>
              ))}
            </div>
          )}
        </Panel>
      )}
      {ev && <EventDetail event={ev} exposure={exp(ev.id)} onClose={() => setSel(null)} />}
    </>
  );
}
